/**
 * ARCH-31 — the client's equivalent of `internal/store/surface_test.go`:
 * every top-level export this package makes, and every i18n key its
 * catalogues carry, is read by something other than its own tests, or is
 * named here with the reason it still stands. An export or key nobody reads
 * is not merely unused code, it is a *rule an agent will read as live* —
 * a seam that looks wired up and enforces nothing.
 *
 * Node `fs` only, deliberately: this walks source text the way the Go guard
 * walks an AST, rather than importing the app and trusting what it happens
 * to evaluate.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const CLIENT_DIR = fileURLToPath(new URL('../../', import.meta.url))
const REPO_ROOT = join(CLIENT_DIR, '..')

/** The feature modules, read off `scripts/modules.mjs` — the one list every such script reads. */
function readModules(): string[] {
  const content = readFileSync(join(REPO_ROOT, 'scripts/modules.mjs'), 'utf8')
  const match = content.match(/export const MODULES = \[([^\]]*)\]/)
  if (!match) throw new Error('scripts/modules.mjs: could not find the MODULES list')
  return [...match[1]!.matchAll(/'([^']+)'/g)].map((m) => m[1]!)
}

const MODULES = readModules()
const SRC_DIR = join(CLIENT_DIR, 'src')
const CLI_DIR = join(CLIENT_DIR, 'cli')

function exists(path: string): boolean {
  try {
    statSync(path)
    return true
  } catch {
    return false
  }
}

/** Every `.ts`/`.vue` file under `dir`, skipping `__tests__/`, specs and declaration files. */
function sourceFiles(dir: string): string[] {
  const out: string[] = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      if (entry === '__tests__' || entry === 'node_modules') continue
      out.push(...sourceFiles(full))
      continue
    }
    if (entry.endsWith('.d.ts') || entry.endsWith('.spec.ts')) continue
    if (entry.endsWith('.ts') || entry.endsWith('.vue')) out.push(full)
  }
  return out
}

/**
 * A comment, or a string literal kept whole so a `//` or `/*` inside one is
 * not taken for a comment. In a `.vue` file, an HTML comment too.
 */
const COMMENT_OR_STRING_RE =
  /(\/\*[\s\S]*?\*\/|\/\/[^\n]*|<!--[\s\S]*?-->)|('(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\[\s\S]|[^`\\])*`)/g

/**
 * The file's text with its comments blanked: a name that survives only in a
 * comment has no reader. Strings stay, since an i18n key is read as one.
 */
function withoutComments(file: string, text: string): string {
  const vue = file.endsWith('.vue')
  return text.replace(COMMENT_OR_STRING_RE, (match, comment: string | undefined) => {
    if (comment === undefined) return match
    if (comment.startsWith('<!--') && !vue) return match
    return comment.replace(/[^\n]/g, ' ')
  })
}

const ROOT_DIRS = [SRC_DIR, ...(exists(CLI_DIR) ? [CLI_DIR] : [])]
const ALL_FILES = ROOT_DIRS.flatMap(sourceFiles)
const FILE_CONTENTS = new Map(
  ALL_FILES.map((file) => [file, withoutComments(file, readFileSync(file, 'utf8'))]),
)

/** `src/api/tables.ts` or `cli/common.ts` — the key prefix every name below is reported under. */
function keyPath(file: string): string {
  return file.startsWith(SRC_DIR) ? relative(SRC_DIR, file) : join('cli', relative(CLI_DIR, file))
}

