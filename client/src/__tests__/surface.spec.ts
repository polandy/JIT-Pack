/** Matches a top-level `export const|let|function|async function|class|type|interface|enum NAME`. */
const EXPORT_RE =
  /^export\s+(?:async\s+function|function|const|let|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm

type ExportDecl = { key: string; name: string; file: string }

function collectExports(): ExportDecl[] {
  const decls: ExportDecl[] = []
  for (const file of ALL_FILES) {
    if (!file.endsWith('.ts')) continue
    const content = FILE_CONTENTS.get(file)!
    for (const match of content.matchAll(EXPORT_RE)) {
      const name = match[1]!
      decls.push({ key: `${keyPath(file)}#${name}`, name, file })
    }
  }
  return decls
}

/** Every identifier-shaped word in every source file, counted per file. */
const WORD_RE = /[A-Za-z_$][\w$]*/g
const WORD_COUNTS = new Map(
  ALL_FILES.map((file) => {
    const counts = new Map<string, number>()
    for (const word of FILE_CONTENTS.get(file)!.matchAll(WORD_RE)) {
      counts.set(word[0], (counts.get(word[0]) ?? 0) + 1)
    }
    return [file, counts] as const
  }),
)

/**
 * Whether `name` is read anywhere but its own declaration: in another file
 * at all, or more than once (the declaration itself) in its own.
 */
function hasReaderOutsideItsDeclaration(name: string, declaringFile: string): boolean {
  for (const [file, counts] of WORD_COUNTS) {
    const count = counts.get(name) ?? 0
    if (count === 0) continue
    if (file === declaringFile) {
      if (count > 1) return true
    } else {
      return true
    }
  }
  return false
}

describe('a name in a comment is not a reader (ARCH-31)', () => {
  it('blanks line, block and template comments, and keeps strings whole', () => {
    const ts = [
      '// onlyInLine {@link onlyInLink}',
      '/** onlyInBlock */',
      "const url = 'https://keptInString' // trailing",
      'read(liveName) /* gone */',
    ].join('\n')
    const stripped = withoutComments('a.ts', ts)
    expect(stripped).not.toMatch(/onlyInLine|onlyInLink|onlyInBlock|trailing|gone/)
    expect(stripped).toMatch(/keptInString/)
    expect(stripped).toMatch(/liveName/)
    expect(stripped.split('\n')).toHaveLength(4)

    const vue = '<!-- onlyInHtml -->\n<p :x="liveName" />'
    expect(withoutComments('a.vue', vue)).not.toMatch(/onlyInHtml/)
    expect(withoutComments('a.vue', vue)).toMatch(/liveName/)
  })
})

describe('every export has a reader outside its own declaration (ARCH-31)', () => {
  const exportDecls = collectExports()

  it('found a measurable number of exports — the guard is not measuring nothing', () => {
    expect(exportDecls.length).toBeGreaterThanOrEqual(500)
  })

  it.each(exportDecls)(
    '$key has a reader outside its own declaration, or is named with a reason',
    (decl) => {
      const used = hasReaderOutsideItsDeclaration(decl.name, decl.file)
      const reason = exportsWithNoProductionReader[decl.key]
      if (used && reason !== undefined) {
        throw new Error(
          `${decl.key} is read outside its declaration but listed as unreachable: ${reason}`,
        )
      }
      if (!used && reason === undefined) {
        throw new Error(
          `${decl.key} has no reader outside its own declaration — delete it, unexport it, or ` +
            `name it in exportsWithNoProductionReader with the reason it is public`,
        )
      }
      expect(used !== (reason !== undefined)).toBe(true)
    },
  )

  it('names only exports that still exist', () => {
    const declared = new Set(exportDecls.map((d) => d.key))
    for (const key of Object.keys(exportsWithNoProductionReader)) {
      expect(declared.has(key), `${key} is named but is no longer an export`).toBe(true)
    }
  })
})

