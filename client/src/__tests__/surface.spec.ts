/** Matches a top-level flat catalogue entry: `  'area.key': …`. */
const CATALOGUE_KEY_RE = /^\s*'([a-zA-Z][\w.]*)'\s*:/gm

/** The area directories the kernel catalogue assembles, read off its own import list. */
function kernelAreas(): string[] {
  const assembler = readFileSync(join(SRC_DIR, 'i18n/messages/en.ts'), 'utf8')
  return [...assembler.matchAll(/^import\s*\{\s*\w+\s*\}\s*from\s*'\.\/(\w+)\/en'/gm)].map(
    (m) => m[1]!,
  )
}

type Catalogue = { enFile: string; deFile: string; keys: string[] }

function readCatalogue(enFile: string, deFile: string): Catalogue {
  const content = readFileSync(enFile, 'utf8')
  const keys = [...content.matchAll(CATALOGUE_KEY_RE)].map((m) => m[1]!)
  return { enFile, deFile, keys }
}

function allCatalogues(): Catalogue[] {
  const kernel = kernelAreas().map((area) =>
    readCatalogue(
      join(SRC_DIR, 'i18n/messages', area, 'en.ts'),
      join(SRC_DIR, 'i18n/messages', area, 'de.ts'),
    ),
  )
  const modules = MODULES.map((module) =>
    readCatalogue(join(SRC_DIR, module, 'i18n/en.ts'), join(SRC_DIR, module, 'i18n/de.ts')),
  )
  return [...kernel, ...modules]
}

const CATALOGUES = allCatalogues()
const CATALOGUE_FILES = new Set(CATALOGUES.flatMap((c) => [c.enFile, c.deFile]))

/** Reader files for the i18n check: every source file except the catalogues themselves. */
const KEY_READER_FILES = ALL_FILES.filter((file) => !CATALOGUE_FILES.has(file))

function isKeyUsed(key: string): boolean {
  if (Object.keys(dynamicKeyPrefixes).some((prefix) => key.startsWith(prefix))) return true
  return KEY_READER_FILES.some((file) => FILE_CONTENTS.get(file)!.includes(key))
}

describe('every i18n key has a reader outside specs and e2e (ARCH-31)', () => {
  const allKeys = CATALOGUES.flatMap((c) => c.keys)

  it('found a measurable number of keys — the guard is not measuring nothing', () => {
    expect(allKeys.length).toBeGreaterThanOrEqual(500)
  })

  it.each(allKeys)('%s is read somewhere outside its own catalogue entry', (key) => {
    expect(
      isKeyUsed(key),
      `${key} is defined but never read — delete it from en.ts and de.ts`,
    ).toBe(true)
  })

  it('names only prefixes a real template literal builds', () => {
    for (const prefix of Object.keys(dynamicKeyPrefixes)) {
      const covers = allKeys.some((key) => key.startsWith(prefix))
      expect(covers, `${prefix} is named in dynamicKeyPrefixes but matches no catalogue key`).toBe(
        true,
      )
    }
  })
})
