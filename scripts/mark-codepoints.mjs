/**
 * Print the code points of the curated mark index (FR-28.2) as a comma-separated
 * `U+XXXX` list — the input both `build-mark-font.sh` and `mark-font-gate.mjs`
 * read, so the font subset and the CSS `unicode-range` can never be derived
 * from two different readings of the index.
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * The index is TypeScript, and this script runs in plain node during a shell
 * build — so the emoji are read out of the source text rather than imported.
 * A regex over `emoji: '…'` is exact here because the field is a string
 * literal by construction and the file is generated by nobody.
 */
export function markCodePoints() {
  const source = readFileSync(join(root, 'client/src/domain/itemMarks.ts'), 'utf8')
  const emoji = [...source.matchAll(/emoji: '([^']+)'/g)].map((m) => m[1])
  if (emoji.length === 0) throw new Error('no entries found in itemMarks.ts')
  const points = new Set()
  for (const mark of emoji) for (const ch of mark) points.add(ch.codePointAt(0))
  return [...points].sort((a, b) => a - b)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(markCodePoints().map((cp) => `U+${cp.toString(16).toUpperCase()}`).join(','))
}
